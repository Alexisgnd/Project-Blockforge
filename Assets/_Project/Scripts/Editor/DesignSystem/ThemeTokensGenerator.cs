using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.IO.Compression;
using System.Text;
using System.Text.RegularExpressions;
using UnityEditor;
using UnityEngine;

// =========================================================
// GENERATEUR DU THEME DEPUIS tokens.json
// Menu : Blockforge > Design System > Generate Theme Tokens
// Lit Branding/blockforge-design-system.zip (tokens.json) et
// reecrit Scripts/Runtime/UI/Theme/BlockforgeTheme.Tokens.cs :
// couleurs des deux themes (dark, hud) + Palette par theme,
// espacements, rayons, controles, opacites, ombres, styles de
// texte. A relancer apres chaque mise a jour du design system ;
// le fichier genere n'est jamais edite a la main.
// Le meme gabarit existe en Python (Tools/DesignSystem/
// gen_theme_tokens.py) pour les environnements sans Unity.
// =========================================================

public static class ThemeTokensGenerator
{
    public const string ZipPath = "Branding/blockforge-design-system.zip";
    public const string OutputPath = "Assets/_Project/Scripts/Runtime/UI/Theme/BlockforgeTheme.Tokens.cs";

    [MenuItem("Blockforge/Design System/Generate Theme Tokens")]
    public static void Generate()
    {
        string json = ReadTokensJson();
        if (json == null)
            return;
        var tokens = (Dictionary<string, object>)MiniJson.Parse(json);
        string source = Render(tokens);
        File.WriteAllText(OutputPath, source, new UTF8Encoding(false));
        AssetDatabase.ImportAsset(OutputPath);
        Debug.Log($"[DesignSystem] Theme regenere : {OutputPath} ({source.Split('\n').Length} lignes).");
    }

    private static string ReadTokensJson()
    {
        if (!File.Exists(ZipPath))
        {
            Debug.LogError($"[DesignSystem] Archive introuvable : {ZipPath} (git lfs pull ?).");
            return null;
        }
        try
        {
            using var zip = ZipFile.OpenRead(ZipPath);
            foreach (var entry in zip.Entries)
            {
                if (!entry.FullName.EndsWith("tokens.json", StringComparison.Ordinal) || entry.FullName.Contains("/ds/"))
                    continue;
                using var reader = new StreamReader(entry.Open(), Encoding.UTF8);
                return reader.ReadToEnd();
            }
            Debug.LogError("[DesignSystem] tokens.json absent de l'archive.");
        }
        catch (Exception e)
        {
            Debug.LogError($"[DesignSystem] Lecture de l'archive impossible : {e.Message}");
        }
        return null;
    }

    // =========================================================
    // RENDU (identique au script Python)
    // =========================================================

    private static readonly CultureInfo Inv = CultureInfo.InvariantCulture;

    private static string Pascal(string name)
    {
        var sb = new StringBuilder();
        foreach (var part in name.Split('-'))
        {
            if (part.Length == 0) continue;
            sb.Append(char.ToUpperInvariant(part[0])).Append(part.Substring(1));
        }
        return sb.ToString();
    }

    private static string HexCall(string value)
    {
        string v = value.TrimStart('#').ToUpperInvariant();
        return v.Length == 6 ? $"Hex(0x{v})" : $"Hex(0x{v.Substring(0, 6)}, 0x{v.Substring(6)})";
    }

    private static float Px(object value)
    {
        string s = Regex.Replace(Convert.ToString(value, Inv) ?? "", "[^0-9.]", "");
        return s.Length == 0 ? 0f : float.Parse(s, Inv);
    }

    private static string F(float v) => v.ToString("0.###", Inv) + "f";

    private static List<object> List(Dictionary<string, object> root, string section, string key = "tokens") =>
        (List<object>)((Dictionary<string, object>)root[section])[key];

    private static string Render(Dictionary<string, object> t)
    {
        var sb = new StringBuilder();
        void W(string line) => sb.Append(line).Append('\n');

        W("// <auto-generated>");
        W("// Genere par Blockforge > Design System > Generate Theme Tokens");
        W("// a partir de Branding/blockforge-design-system.zip -> tokens.json.");
        W("// NE PAS EDITER A LA MAIN : relancer le menu apres une mise a jour du");
        W("// design system. Les helpers (Num, Duration, EaseOut, alias) sont dans");
        W("// BlockforgeTheme.cs, les metriques d'ecran dans BlockforgeTheme.Layout.cs.");
        W("// </auto-generated>");
        W("");
        W("using UnityEngine;");
        W("");
        W("public static partial class BlockforgeTheme");
        W("{");
        W($"    public const string TokensVersion = \"{Convert.ToString(t.TryGetValue("version", out var ver) ? ver : "", Inv)}\";");
        W("");

        var colors = List(t, "color");

        void EmitColors(string theme, string indent)
        {
            foreach (Dictionary<string, object> c in colors)
            {
                if (c["value"] is Dictionary<string, object> v)
                    W($"{indent}public static readonly Color {Pascal((string)c["name"])} = {HexCall((string)v[theme])};");
            }
            W($"{indent}// alias");
            foreach (Dictionary<string, object> c in colors)
            {
                if (c["value"] is string alias)
                    W($"{indent}public static readonly Color {Pascal((string)c["name"])} = {Pascal(alias.Trim('{', '}'))};");
            }
        }

        W("    // ----- Couleurs, theme \"dark\" (menus, garage, hub) -----");
        EmitColors("dark", "    ");
        W("");
        W("    // ----- Couleurs, theme \"hud\" (overlay de match, fin de match, resultats) -----");
        W("    public static class Hud");
        W("    {");
        EmitColors("hud", "        ");
        W("    }");
        W("");
        W("    // ----- Palette : les memes jetons, choisis par theme (widgets partages) -----");
        W("    public sealed class Palette");
        W("    {");
        W("        public readonly DSTheme Theme;");
        foreach (Dictionary<string, object> c in colors)
            W($"        public readonly Color {Pascal((string)c["name"])};");
        W("");
        W("        public Palette(DSTheme theme)");
        W("        {");
        W("            Theme = theme;");
        W("            bool hud = theme == DSTheme.Hud;");
        foreach (Dictionary<string, object> c in colors)
        {
            string n = Pascal((string)c["name"]);
            W($"            {n} = hud ? Hud.{n} : BlockforgeTheme.{n};");
        }
        W("        }");
        W("    }");
        W("");
        W("    public static readonly Palette DarkPalette = new(DSTheme.Dark);");
        W("    public static readonly Palette HudPalette = new(DSTheme.Hud);");
        W("    public static Palette PaletteFor(DSTheme theme) => theme == DSTheme.Hud ? HudPalette : DarkPalette;");
        W("");
        W("    // ----- Espacements (px a 1920 x 1080) -----");
        foreach (Dictionary<string, object> s in List(t, "spacing"))
            W($"    public const float {Pascal((string)s["name"])} = {F(Px(s["value"]))};");
        W("");
        W("    // ----- Rayons -----");
        foreach (Dictionary<string, object> s in List(t, "radius"))
            W($"    public const float {Pascal((string)s["name"])} = {F(Px(s["value"]))};");
        W("");
        W("    // ----- Controles -----");
        foreach (Dictionary<string, object> s in List(t, "control"))
            W($"    public const float {Pascal((string)s["name"])} = {F(Px(s["value"]))};");
        W("");
        W("    // ----- Opacites -----");
        foreach (Dictionary<string, object> s in List(t, "opacity"))
            W($"    public const float {Pascal((string)s["name"])} = {F(float.Parse(Convert.ToString(s["value"], Inv), Inv))};");
        W("");
        W("    // ----- Ombres (x, y, flou, couleur) -----");
        var shadow = new Regex(@"\s*(-?[\d.]+)(?:px)?\s+(-?[\d.]+)(?:px)?\s+(-?[\d.]+)(?:px)?\s+rgba\(\s*(\d+),\s*(\d+),\s*(\d+),\s*([\d.]+)\)");
        foreach (Dictionary<string, object> s in List(t, "shadow"))
        {
            var m = shadow.Match((string)s["value"]);
            if (!m.Success) continue;
            string rgb = $"0x{int.Parse(m.Groups[4].Value):X2}{int.Parse(m.Groups[5].Value):X2}{int.Parse(m.Groups[6].Value):X2}";
            W($"    public static readonly ShadowSpec {Pascal((string)s["name"])} = new({F(float.Parse(m.Groups[1].Value, Inv))}, {F(float.Parse(m.Groups[2].Value, Inv))}, {F(float.Parse(m.Groups[3].Value, Inv))}, Hex({rgb}), {F(float.Parse(m.Groups[7].Value, Inv))});");
        }
        W("");
        W("    // ----- Styles de texte (taille / interligne / graisse / interlettrage em) -----");
        W("    public static class Type");
        W("    {");
        foreach (Dictionary<string, object> g in List(t, "type", "groups"))
        {
            string family = (string)g["family"];
            family = char.ToUpperInvariant(family[0]) + family.Substring(1);
            foreach (Dictionary<string, object> s in (List<object>)g["styles"])
            {
                float ls = s.TryGetValue("letterSpacing", out var lsv) && lsv != null ? Px(lsv) : 0f;
                W($"        public static readonly TypeSpec {Pascal((string)s["name"])} = new(FontFamily.{family}, {F(Px(s["fontSize"]))}, {F(Px(s["lineHeight"]))}, {Convert.ToInt32(s["fontWeight"], Inv)}, {F(ls)});");
            }
        }
        W("    }");
        W("}");
        return sb.ToString();
    }

    // =========================================================
    // LECTEUR JSON MINIMAL (objets -> Dictionary, tableaux -> List,
    // nombres -> double, le reste -> string / bool / null)
    // =========================================================

    private static class MiniJson
    {
        public static object Parse(string json)
        {
            int i = 0;
            return Value(json, ref i);
        }

        private static void Ws(string s, ref int i)
        {
            while (i < s.Length && char.IsWhiteSpace(s[i])) i++;
        }

        private static object Value(string s, ref int i)
        {
            Ws(s, ref i);
            char c = s[i];
            if (c == '{') return Obj(s, ref i);
            if (c == '[') return Arr(s, ref i);
            if (c == '"') return Str(s, ref i);
            if (s.Length - i >= 4 && s.Substring(i, 4) == "true") { i += 4; return true; }
            if (s.Length - i >= 5 && s.Substring(i, 5) == "false") { i += 5; return false; }
            if (s.Length - i >= 4 && s.Substring(i, 4) == "null") { i += 4; return null; }
            int start = i;
            while (i < s.Length && "+-0123456789.eE".IndexOf(s[i]) >= 0) i++;
            return double.Parse(s.Substring(start, i - start), Inv);
        }

        private static Dictionary<string, object> Obj(string s, ref int i)
        {
            var d = new Dictionary<string, object>();
            i++; // {
            Ws(s, ref i);
            if (s[i] == '}') { i++; return d; }
            while (true)
            {
                Ws(s, ref i);
                string key = Str(s, ref i);
                Ws(s, ref i);
                i++; // :
                d[key] = Value(s, ref i);
                Ws(s, ref i);
                if (s[i] == ',') { i++; continue; }
                i++; // }
                return d;
            }
        }

        private static List<object> Arr(string s, ref int i)
        {
            var l = new List<object>();
            i++; // [
            Ws(s, ref i);
            if (s[i] == ']') { i++; return l; }
            while (true)
            {
                l.Add(Value(s, ref i));
                Ws(s, ref i);
                if (s[i] == ',') { i++; continue; }
                i++; // ]
                return l;
            }
        }

        private static string Str(string s, ref int i)
        {
            var sb = new StringBuilder();
            i++; // "
            while (s[i] != '"')
            {
                if (s[i] == '\\')
                {
                    i++;
                    switch (s[i])
                    {
                        case 'n': sb.Append('\n'); break;
                        case 't': sb.Append('\t'); break;
                        case 'r': sb.Append('\r'); break;
                        case 'u': sb.Append((char)Convert.ToInt32(s.Substring(i + 1, 4), 16)); i += 4; break;
                        default: sb.Append(s[i]); break;
                    }
                }
                else sb.Append(s[i]);
                i++;
            }
            i++; // "
            return sb.ToString();
        }
    }
}
