#!/usr/bin/env python3
"""Generate BlockforgeTheme.Tokens.cs from the design system's tokens.json.
Mirror of the C# editor generator (ThemeTokensGenerator.cs): same template."""
import json, re, sys

src, dst = sys.argv[1], sys.argv[2]
t = json.load(open(src))

def pascal(name):
    return "".join(p[:1].upper() + p[1:] for p in name.split("-"))

def hexparse(v):
    v = v.lstrip("#")
    if len(v) == 6:
        return f"Hex(0x{v.upper()})"
    return f"Hex(0x{v[:6].upper()}, 0x{v[6:].upper()})"

def px(v):
    return float(re.sub(r"[^0-9.]", "", v) or "0")

lines = []
w = lines.append
w("// <auto-generated>")
w("// Genere par Blockforge > Design System > Generate Theme Tokens")
w("// a partir de Branding/blockforge-design-system.zip -> tokens.json.")
w("// NE PAS EDITER A LA MAIN : relancer le menu apres une mise a jour du")
w("// design system. Les helpers (Num, Duration, EaseOut, alias) sont dans")
w("// BlockforgeTheme.cs, les metriques d'ecran dans BlockforgeTheme.Layout.cs.")
w("// </auto-generated>")
w("")
w("using UnityEngine;")
w("")
w("public static partial class BlockforgeTheme")
w("{")
w(f"    public const string TokensVersion = \"{t.get('version', '')}\";")
w("")

colors = t["color"]["tokens"]
aliases = {}

def emit_colors(theme, indent):
    # Valeurs directes d'abord, alias ensuite : les champs statiques
    # s'initialisent dans l'ordre du fichier.
    for c in colors:
        v = c["value"]
        if isinstance(v, dict):
            w(f"{indent}public static readonly Color {pascal(c['name'])} = {hexparse(v[theme])};")
    w(f"{indent}// alias")
    for c in colors:
        v = c["value"]
        if not isinstance(v, dict):
            w(f"{indent}public static readonly Color {pascal(c['name'])} = {pascal(str(v).strip('{}'))};")

w("    // ----- Couleurs, theme \"dark\" (menus, garage, hub) -----")
emit_colors("dark", "    ")
w("")
w("    // ----- Couleurs, theme \"hud\" (overlay de match, fin de match, resultats) -----")
w("    public static class Hud")
w("    {")
emit_colors("hud", "        ")
w("    }")
w("")
w("    // ----- Palette : les memes jetons, choisis par theme (widgets partages) -----")
w("    public sealed class Palette")
w("    {")
w("        public readonly DSTheme Theme;")
for c in colors:
    w(f"        public readonly Color {pascal(c['name'])};")
w("")
w("        public Palette(DSTheme theme)")
w("        {")
w("            Theme = theme;")
w("            bool hud = theme == DSTheme.Hud;")
for c in colors:
    n = pascal(c['name'])
    w(f"            {n} = hud ? Hud.{n} : BlockforgeTheme.{n};")
w("        }")
w("    }")
w("")
w("    public static readonly Palette DarkPalette = new(DSTheme.Dark);")
w("    public static readonly Palette HudPalette = new(DSTheme.Hud);")
w("    public static Palette PaletteFor(DSTheme theme) => theme == DSTheme.Hud ? HudPalette : DarkPalette;")
w("")
w("    // ----- Espacements (px a 1920 x 1080) -----")
for s in t["spacing"]["tokens"]:
    w(f"    public const float {pascal(s['name'])} = {px(s['value']):g}f;")
w("")
w("    // ----- Rayons -----")
for s in t["radius"]["tokens"]:
    w(f"    public const float {pascal(s['name'])} = {px(s['value']):g}f;")
w("")
w("    // ----- Controles -----")
for s in t["control"]["tokens"]:
    w(f"    public const float {pascal(s['name'])} = {px(s['value']):g}f;")
w("")
w("    // ----- Opacites -----")
for s in t["opacity"]["tokens"]:
    w(f"    public const float {pascal(s['name'])} = {float(s['value']):g}f;")
w("")
w("    // ----- Ombres (x, y, flou, couleur) -----")
for s in t["shadow"]["tokens"]:
    m = re.match(r"\s*(-?[\d.]+)(?:px)?\s+(-?[\d.]+)(?:px)?\s+(-?[\d.]+)(?:px)?\s+rgba\(\s*(\d+),\s*(\d+),\s*(\d+),\s*([\d.]+)\)", s["value"])
    x, y, b, r, g, bl, a = m.groups()
    w(f"    public static readonly ShadowSpec {pascal(s['name'])} = new({float(x):g}f, {float(y):g}f, {float(b):g}f, Hex(0x{int(r):02X}{int(g):02X}{int(bl):02X}), {float(a):g}f);")
w("")
w("    // ----- Styles de texte (taille / interligne / graisse / interlettrage em) -----")
w("    public static class Type")
w("    {")
for g in t["type"]["groups"]:
    for s in g["styles"]:
        n = pascal(s["name"])
        ls = px(s.get("letterSpacing", "0")) if s.get("letterSpacing") else 0.0
        w(f"        public static readonly TypeSpec {n} = new(FontFamily.{g['family'].capitalize()}, {px(s['fontSize']):g}f, {px(s['lineHeight']):g}f, {int(s['fontWeight'])}, {ls:g}f);")
w("    }")
w("}")
open(dst, "w", newline="\n").write("\n".join(lines) + "\n")
print(f"wrote {dst} ({len(lines)} lines)")
